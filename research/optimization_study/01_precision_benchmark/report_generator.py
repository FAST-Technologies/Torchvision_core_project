"""
Генерация отчётов по результатам бенчмарка точности.
"""

import pandas as pd
from pathlib import Path
from typing import Dict, List, Optional, Union
from datetime import datetime
import json

from .utils import format_time, format_speedup


class ReportGenerator:
    """
    Генератор отчётов в различных форматах.

    Поддерживаемые форматы:
    - Markdown (.md) — для документации
    - JSON (.json) — для программной обработки
    - CSV (.csv) — для анализа в Excel
    - HTML (.html) — для просмотра в браузере
    """

    def __init__(self, output_dir: str = "./reports"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_markdown(
        self,
        df: pd.DataFrame,
        summary: Dict,
        title: str = "Precision Benchmark Report",
        output_file: Optional[str] = None,
    ) -> Path:
        """Генерация отчёта в формате Markdown."""
        if output_file is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_file = f"precision_report_{timestamp}.md"

        output_path = self.output_dir / output_file

        lines = [
            f"# {title}",
            "",
            f"*Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*",
            "",
            "## 📋 Summary",
            "",
            f"- **Methods tested**: {summary.get('total_methods', 0)}",
            f"- **Precisions tested**: {summary.get('total_precisions', 0)}",
            f"- **Total configurations**: {summary.get('total_runs', 0)}",
            "",
        ]

        # Таблица времени по прецизионным режимам
        if "avg_time_by_precision" in summary:
            lines.extend(
                [
                    "## ⏱️  Average Time by Precision",
                    "",
                    "| Precision | Avg Time | Speedup vs FP32 |",
                    "|-----------|----------|----------------|",
                ]
            )
            for prec in ["fp32", "fp16", "bf16", "int8"]:
                if prec in summary["avg_time_by_precision"]:
                    time_val = summary["avg_time_by_precision"][prec]
                    speedup = (
                        summary.get("avg_time_by_precision", {}).get("fp32", time_val)
                        / time_val
                        if time_val > 0
                        else 1
                    )
                    lines.append(
                        f"| {prec} | {format_time(time_val/1000)} | {format_speedup(speedup)} |"
                    )
            lines.append("")

        # Таблица точности
        if "avg_agreement_by_precision" in summary:
            lines.extend(
                [
                    "## 🎯 Pixel Agreement vs FP32",
                    "",
                    "| Precision | Agreement | Status |",
                    "|-----------|-----------|--------|",
                ]
            )
            for prec in ["fp32", "fp16", "bf16", "int8"]:
                if prec in summary["avg_agreement_by_precision"]:
                    agree = summary["avg_agreement_by_precision"][prec]
                    status = "✅" if agree > 0.999 else "⚠️" if agree > 0.99 else "❌"
                    lines.append(f"| {prec} | {agree*100:.4f}% | {status} |")
            lines.append("")

        # Детальная таблица результатов
        lines.extend(
            [
                "## 🔍 Detailed Results",
                "",
                "```",
                df.to_string(index=False),
                "```",
                "",
            ]
        )

        # Рекомендации
        lines.extend(
            [
                "## 💡 Recommendations",
                "",
                "Based on the benchmark results:",
                "",
            ]
        )

        if "best_speedup" in summary:
            best = summary["best_speedup"]
            lines.append(
                f"- For maximum speed: use **{best['precision']}** precision "
                f"with `{best['method']}` method ({format_speedup(best['value'])} speedup)"
            )

        # Проверка точности
        if "avg_agreement_by_precision" in summary:
            safe_precisions = [
                p for p, a in summary["avg_agreement_by_precision"].items() if a > 0.999
            ]
            if safe_precisions:
                lines.append(
                    f"- For production with minimal accuracy loss: "
                    f"use {', '.join(safe_precisions)} (agreement >99.9%)"
                )

        lines.append("")
        lines.append("---")
        lines.append("*Report generated by PrecisionBenchmark*")

        output_path.write_text("\n".join(lines), encoding="utf-8")
        return output_path

    def generate_json(
        self,
        df: pd.DataFrame,
        summary: Dict,
        output_file: Optional[str] = None,
    ) -> Path:
        """Генерация отчёта в формате JSON."""
        if output_file is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_file = f"precision_report_{timestamp}.json"

        output_path = self.output_dir / output_file

        report = {
            "metadata": {
                "generated_at": datetime.now().isoformat(),
                "title": "Precision Benchmark Report",
            },
            "summary": summary,
            "results": df.to_dict(orient="records"),
        }

        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, ensure_ascii=False, default=str)

        return output_path

    def generate_csv(
        self,
        df: pd.DataFrame,
        output_file: Optional[str] = None,
    ) -> Path:
        """Экспорт результатов в CSV."""
        if output_file is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_file = f"precision_results_{timestamp}.csv"

        output_path = self.output_dir / output_file
        df.to_csv(output_path, index=False)
        return output_path

    def generate_all(
        self,
        df: pd.DataFrame,
        summary: Dict,
        base_name: Optional[str] = None,
    ) -> Dict[str, Path]:
        """Генерация отчётов во всех форматах."""
        if base_name is None:
            base_name = f"precision_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}"

        return {
            "markdown": self.generate_markdown(
                df, summary, output_file=f"{base_name}.md"
            ),
            "json": self.generate_json(df, summary, output_file=f"{base_name}.json"),
            "csv": self.generate_csv(df, output_file=f"{base_name}.csv"),
        }
